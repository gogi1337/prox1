#!/usr/bin/env python3
"""Regenerates src/font_atlas.h: a 16x6 grid of 9x18 anti-aliased glyphs
(ASCII 32..126, plus a solid block in the last cell used for filled rectangles).
Font: DejaVu Sans Mono (Bitstream Vera licence, free to embed)."""
from PIL import Image, ImageDraw, ImageFont
import sys

CELL_W, CELL_H, COLS, ROWS = 9, 18, 16, 6
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"

font = ImageFont.truetype(FONT, 15)
img = Image.new("L", (CELL_W * COLS, CELL_H * ROWS), 0)
draw = ImageDraw.Draw(img)
for code in range(32, 127):
    i = code - 32
    draw.text(((i % COLS) * CELL_W, (i // COLS) * CELL_H + 14), chr(code), font=font, fill=255, anchor="ls")
last = COLS * ROWS - 1  # solid cell
draw.rectangle([(last % COLS) * CELL_W, (last // COLS) * CELL_H,
                (last % COLS + 1) * CELL_W - 1, (last // COLS + 1) * CELL_H - 1], fill=255)

data = list(img.getdata())
out = ["// Generated by tools/gen_font.py - do not edit. Font: DejaVu Sans Mono (Bitstream Vera licence).",
       "#ifndef FONT_ATLAS_H", "#define FONT_ATLAS_H", "",
       f"#define FONT_CELL_W {CELL_W}", f"#define FONT_CELL_H {CELL_H}",
       f"#define FONT_COLS {COLS}", f"#define FONT_ROWS {ROWS}",
       f"#define FONT_SOLID_CELL {last}", "",
       "static const unsigned char FONT_ATLAS[] = {"]
for r in range(0, len(data), 24):
    out.append("    " + ",".join(str(v) for v in data[r:r + 24]) + ",")
out += ["};", "", "#endif // FONT_ATLAS_H", ""]
open("src/font_atlas.h", "w").write("\n".join(out))
print("wrote src/font_atlas.h", len(data), "bytes")
